CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500)
);

CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    employee_number VARCHAR(30) NOT NULL UNIQUE,
    last_name VARCHAR(100) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    position VARCHAR(120) NOT NULL,
    hire_date DATE NOT NULL,
    department_id BIGINT NOT NULL REFERENCES departments(id),
    manager_id BIGINT REFERENCES employees(id),
    CONSTRAINT employee_not_own_manager CHECK (manager_id IS NULL OR manager_id <> id)
);

CREATE INDEX idx_employees_department ON employees(department_id);
CREATE INDEX idx_employees_manager ON employees(manager_id);

CREATE TABLE contracts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    type VARCHAR(20) NOT NULL CHECK (type IN ('CDI', 'CDD', 'STAGE')),
    start_date DATE NOT NULL,
    end_date DATE,
    gross_salary NUMERIC(12, 2) NOT NULL CHECK (gross_salary > 0),
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    CONSTRAINT contract_dates_valid CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT temporary_contract_has_end CHECK (type NOT IN ('CDD', 'STAGE') OR end_date IS NOT NULL)
);

CREATE INDEX idx_contracts_employee_start ON contracts(employee_id, start_date DESC);

CREATE TABLE leave_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    days_per_year INTEGER NOT NULL CHECK (days_per_year >= 0)
);

CREATE TABLE leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    leave_type_id BIGINT NOT NULL REFERENCES leave_types(id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    working_days INTEGER NOT NULL CHECK (working_days > 0),
    reason VARCHAR(1000) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('EN_ATTENTE', 'APPROUVEE', 'REFUSEE', 'ANNULEE')),
    manager_comment VARCHAR(1000),
    CONSTRAINT leave_request_dates_valid CHECK (end_date >= start_date)
);

CREATE INDEX idx_leave_request_employee_status ON leave_requests(employee_id, status);
CREATE INDEX idx_leave_request_dates ON leave_requests(start_date, end_date);

